"""Regenerate the current-addon fixtures in fixtures/ from the real addon running in a Lua 5.1 VM.

    python tools/make_fixtures.py          # write fixtures/savedvariables/ForeverTracker.current.lua and
                                           # fixtures/batches/current-batch.json
    python tools/make_fixtures.py --check  # exit 1 if they differ from what the addon writes now

The addon runs against the mocked client (addon/tests/lib/wowmock.lua), so these files show the exact
shape the current addon writes. The players and runs are fictional, the files are flagged synthetic, and
they are not evidence of real Forever client behaviour.

``ForeverTracker.sample.lua`` and ``sample-batch.json`` were written by addon 0.1.0 and are kept as they
are: they are the old-payload fixture (backend/tests/test_contract.py reads both).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "addon" / "tests"))

from forevertracker_sv import extract_batches, parse_savedvariables  # noqa: E402
from harness import new_runtime, savedvariables_text  # noqa: E402

SV_PATH = REPO / "fixtures" / "savedvariables" / "ForeverTracker.current.lua"
BATCH_PATH = REPO / "fixtures" / "batches" / "current-batch.json"
HEADER = "-- SYNTHETIC SAMPLE generated by tools/make_fixtures.py (addon in a mocked client). Not real players.\n"

# Two runs: one completed through the dungeon finder (a wipe, then the kill, a death); one the player marks
# as completed. A pet and a player outside the group appear in the meter. Then a probe report.
SCENARIO = """
boot()
Mock.fire("GROUP_ROSTER_UPDATE")
Mock.advance(1)
Mock.enterDungeon({ name = "Hall of Thanes", mapId = 990001 })
Mock.advance(30)
Mock.startCombat()
Mock.advance(40)
Mock.endCombat(40, { Autumn = { damage_done = 30000, interrupts = 1 }, Mah = { damage_done = 18000 },
  Phineas = { healing_done = 21000 }, Asha = { damage_done = 26000 }, Thalen = { damage_done = 24000 }, Wolf = { damage_done = 900 } })
Mock.advance(15)
Mock.fire("ENCOUNTER_START", 3001, "Thane Ironvow", 1, 5)
Mock.startCombat()
Mock.advance(30)
Mock.endCombat(30, { Autumn = { damage_done = 20000 }, Mah = { damage_done = 9000 }, Phineas = { healing_done = 15000 } })
Mock.fire("ENCOUNTER_END", 3001, "Thane Ironvow", 1, 5, 0, {})
Mock.advance(60)
Mock.fire("ENCOUNTER_START", 3001, "Thane Ironvow", 1, 5)
Mock.startCombat()
Mock.advance(45)
Mock.setDead("Mah", true)
Mock.advance(30)
Mock.endCombat(75, { Autumn = { damage_done = 60000 }, Mah = { damage_done = 20000, deaths = 1 },
  Phineas = { healing_done = 50000 }, Asha = { damage_done = 55000, interrupts = 2 }, Thalen = { damage_done = 52000 } })
Mock.fire("ENCOUNTER_END", 3001, "Thane Ironvow", 1, 5, 1, {})
Mock.advance(20)
Mock.setDead("Mah", false)
Mock.fire("LFG_COMPLETION_REWARD")
Mock.advance(30)
Mock.leaveInstance()
Mock.advance(600)
Mock.enterDungeon({ name = "Ruins of Lordaeron", mapId = 990002 })
Mock.advance(20)
Mock.startCombat()
Mock.advance(50)
Mock.endCombat(50, { Autumn = { damage_done = 40000 }, Stranger = { damage_done = 7000 } }, { strangers = { Stranger = "Player-4620-00FFFF" } })
Mock.advance(15)
Mock.slash("complete")
Mock.advance(5)
Mock.leaveInstance()
Mock.advance(5)
Mock.slash("probe")
ForeverTrackerDB.synthetic = true
Mock.saveVariables()
"""


def current_savedvariables() -> str:
    lua = new_runtime()
    lua.execute(SCENARIO)
    return HEADER + savedvariables_text(lua)


def current_batch(text: str) -> str:
    (batch,) = extract_batches(parse_savedvariables(text), created_at=1792000000)
    return json.dumps(batch, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    text = current_savedvariables()
    batch = current_batch(text)
    if "--check" in argv:
        stale = [p for p, want in ((SV_PATH, text), (BATCH_PATH, batch)) if not p.exists() or p.read_text(encoding="utf-8") != want]
        for p in stale:
            print(f"{p.relative_to(REPO)} is not what the addon writes now: run python tools/make_fixtures.py", file=sys.stderr)
        return 1 if stale else 0
    for path, content in ((SV_PATH, text), (BATCH_PATH, batch)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
