"""Regenerate the sample files in fixtures/ from the real addon running in a Lua 5.1 VM.

    python tools/make_fixtures.py

The addon runs against the mocked client (addon/tests/lib/wowmock.lua), so these files show
the exact shape the addon writes. The players and the run are fictional, the files are flagged
synthetic, and they are not evidence of real Forever client behaviour.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "addon" / "tests"))

from forevertracker_sv import extract_batches, parse_savedvariables  # noqa: E402
from harness import new_runtime, savedvariables_text  # noqa: E402

SCENARIO = """
boot()
Mock.enterDungeon({ name = "Hall of Thanes", mapId = 990001 })
Mock.advance(30)
Mock.startCombat()
Mock.advance(40)
Mock.endCombat(40, { Autumn = { damage_done = 30000, interrupts = 1 }, Mah = { damage_done = 18000 },
  Phineas = { healing_done = 21000 }, Asha = { damage_done = 26000 }, Thalen = { damage_done = 24000 } })
Mock.advance(15)
Mock.fire("ENCOUNTER_START", 3001, "Thane Ironvow", 1, 5)
Mock.startCombat()
Mock.advance(45)
Mock.setDead("Mah", true)
Mock.advance(30)
Mock.endCombat(75, { Autumn = { damage_done = 60000 }, Mah = { damage_done = 20000, deaths = 1 },
  Phineas = { healing_done = 50000 }, Asha = { damage_done = 55000, interrupts = 2 }, Thalen = { damage_done = 52000 } })
Mock.fire("ENCOUNTER_END", 3001, "Thane Ironvow", 1, 5, 1, {})
Mock.advance(20)
Mock.setDead("Mah", false)
Mock.fire("LFG_COMPLETION_REWARD")
Mock.advance(30)
Mock.leaveInstance()
Mock.advance(5)
Mock.slash("probe")
ForeverTrackerDB.synthetic = true
Mock.saveVariables()
"""


def main() -> None:
    lua = new_runtime()
    lua.execute(SCENARIO)
    text = "-- SYNTHETIC SAMPLE generated by tools/make_fixtures.py (addon in a mocked client). Not real players.\n"
    text += savedvariables_text(lua)
    sv_path = REPO / "fixtures" / "savedvariables" / "ForeverTracker.sample.lua"
    sv_path.parent.mkdir(parents=True, exist_ok=True)
    sv_path.write_text(text, encoding="utf-8")
    batches = extract_batches(parse_savedvariables(text), created_at=1792000000)
    batch_path = REPO / "fixtures" / "batches" / "sample-batch.json"
    batch_path.parent.mkdir(parents=True, exist_ok=True)
    batch_path.write_text(json.dumps(batches[0], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {sv_path.relative_to(REPO)} and {batch_path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
